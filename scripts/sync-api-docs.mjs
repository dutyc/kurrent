import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const pages = [
  {
    source: 'api/control-plane-api.zh-CN.md',
    target: 'docs/reference/api.md',
    title: 'API 参考',
  },
  {
    source: 'api/control-plane-api.en.md',
    target: 'docs/en/reference/api.md',
    title: 'API Reference',
  },
]

for (const { source, target, title } of pages) {
  const body = (await readFile(resolve(root, source), 'utf8')).replace(/^\uFEFF/, '')
  const header = [
    '---',
    `title: ${title}`,
    'outline: 2',
    '---',
    '',
    `<!-- Generated by scripts/sync-api-docs.mjs from ${source}; do not edit directly. -->`,
    '',
  ].join('\n') + '\n'
  const output = resolve(root, target)
  await mkdir(dirname(output), { recursive: true })
  await writeFile(output, header + body, 'utf8')
  console.log(`synced ${source} -> ${target}`)
}
